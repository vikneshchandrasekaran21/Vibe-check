#!/usr/bin/env python3
"""Build single-file and tool-specific versions of the vibe-check skill.

Source of truth: skills/vibe-check/SKILL.md + skills/vibe-check/references/*.md
Outputs:      dist/vibe-check.md and adapters/** (do not edit those by hand)

Usage: python3 scripts/build.py          # write outputs
       python3 scripts/build.py --check  # fail if outputs are out of date (CI)
"""
from __future__ import annotations

import io
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "skills" / "vibe-check"
REF_ORDER = [
    "security.md",
    "reliability.md",
    "devops.md",
    "functional-qa.md",
    "legal-privacy.md",
    "launch-ux.md",
    "platforms.md",
    "lawsuits.md",
    "supply-chain.md",
    "vulnerabilities.md",
    "hunt.md",
    "maintainability.md",
    "ai-features.md",
    "ai-agents.md",
    "kids-education.md",
    "health.md",
    "fintech.md",
    "policies.md",
    "enterprise.md",
    "mobile.md",
    "community.md",
    "cloud-infra.md",
    "desktop-extensions.md",
    "i18n.md",
    "live-tests.md",
    "report-template.md",
    "fixes.md",
    "sweep-patterns.md",
    "standards.md",
]
DESCRIPTION = (
    "Full code audit for AI-built (vibe-coded) apps before launch: security, auth, data, reliability, "
    "known vulnerabilities, ops, AI features, legal/privacy and UX. Not a visual design review."
)
HEADER = (
    "<!-- GENERATED by scripts/build.py from skills/vibe-check/. "
    "Do not edit by hand. https://github.com/vikneshchandrasekaran21/Vibe-check -->\n\n"
)


def strip_frontmatter(text: str) -> str:
    return re.sub(r"\A---\n.*?\n---\n", "", text, count=1, flags=re.S).lstrip()


def yq(s: str) -> str:
    """A YAML double-quoted string (JSON strings are valid YAML), so ': ' and '#' can't break the header."""
    import json
    return json.dumps(s, ensure_ascii=False)


def sweep_patterns() -> str:
    """references/sweep-patterns.md, generated from scripts/sweep.py so the two never drift apart."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("vc_sweep", SKILL_DIR / "scripts" / "sweep.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    out = [
        "# Sweep patterns",
        "",
        "<!-- GENERATED by scripts/build.py from scripts/sweep.py. Do not edit by hand. -->",
        "",
        "`scripts/sweep.py` searches every file for these patterns (and git history for the secret ones). "
        "If Python can't run, search for them yourself, file by file, and give every match a verdict in the ledger "
        "(`FINDING <check ID>` or `RULED OUT` with the reason). A match is a lead, not a finding.",
        "",
    ]
    for pid, check, title, rx, flags, kind in mod.PATTERNS:
        ci = " (case-insensitive)" if flags & 2 else ""
        out.append(f"- **{pid}** → `{check}`: {title}{' · also in git history' if kind == 'secret' else ''}{ci}")
        out.append("  ```regex\n  " + rx + "\n  ```")
    out += ["- **ENV-TRACKED** → `SEC-022`: a `.env` file (not `.example`) is tracked by git (`git ls-files`)", ""]
    return "\n".join(out)


def single_file() -> str:
    body = strip_frontmatter((SKILL_DIR / "SKILL.md").read_text())
    # In the single file, references are inlined below, so point to sections instead of files.
    body = re.sub(r"`references/([a-z-]+)\.md`", r"the **\1** section below", body)
    body = re.sub(r"`([a-z-]+)\.md`", r"the **\1** section below", body)
    parts = [HEADER, body.rstrip(), "\n\n---\n\n# Reference checklists\n"]
    for name in REF_ORDER:
        ref = (SKILL_DIR / "references" / name).read_text().rstrip()
        ref = re.sub(r"`([a-z-]+)\.md`", r"the **\1** section", ref)
        # demote headings one level so they nest under "Reference checklists"
        ref = re.sub(r"^(#{1,5}) ", lambda m: "#" + m.group(1) + " ", ref, flags=re.M)
        parts.append(f"\n<a id=\"{name[:-3]}\"></a>\n\n{ref}\n")
    return "".join(parts)


def skill_zip() -> bytes:
    """Deterministic zip for the Claude app's 'Upload skill' (Settings > Customize > Skills)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        files = ([SKILL_DIR / "SKILL.md"] + sorted((SKILL_DIR / "references").glob("*.md"))
                 + sorted((SKILL_DIR / "scripts").glob("*.py")))
        for f in files:
            text = f.read_text()
            if f.name == "SKILL.md":
                # keep only name + description in the uploaded copy for maximum compatibility
                fm = re.match(r"---\n(.*?)\n---\n", text, re.S).group(1)
                keep = [l for l in fm.splitlines() if l.startswith(("name:", "description:"))]
                text = "---\n" + "\n".join(keep) + "\n---\n" + strip_frontmatter(text)
            info = zipfile.ZipInfo(f"vibe-check/{f.relative_to(SKILL_DIR).as_posix()}", (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if f.suffix == ".py" else 0o644) << 16
            z.writestr(info, text)
    return buf.getvalue()


def outputs() -> dict[Path, str | bytes]:
    patterns = sweep_patterns()
    pat_path = SKILL_DIR / "references" / "sweep-patterns.md"
    if not pat_path.exists() or pat_path.read_text() != patterns:
        if "--check" in sys.argv:
            return {pat_path: patterns}
        pat_path.write_text(patterns)
    full = single_file()
    body = full[len(HEADER):]
    out: dict[Path, str] = {}
    out[ROOT / "dist" / "vibe-check.md"] = full

    # Cursor rule (manual / agent-requested)
    out[ROOT / "adapters/cursor/.cursor/rules/vibe-check.mdc"] = (
        "---\ndescription: " + yq(DESCRIPTION + " Use before shipping or when asked to audit the app.") + "\n"
        "globs:\nalwaysApply: false\n---\n\n" + HEADER + body
    )
    # GitHub Copilot prompt file (/vibe-check in Copilot Chat)
    out[ROOT / "adapters/copilot/.github/prompts/vibe-check.prompt.md"] = (
        "---\nmode: agent\ndescription: " + yq(DESCRIPTION) + "\n---\n\n" + HEADER + body
    )
    # Windsurf workflow (/vibe-check in Cascade)
    out[ROOT / "adapters/windsurf/.windsurf/workflows/vibe-check.md"] = (
        "---\ndescription: " + yq(DESCRIPTION) + "\n---\n\n" + HEADER + body
    )
    # Cline / Roo workflow (/vibe-check.md)
    out[ROOT / "adapters/cline/.clinerules/workflows/vibe-check.md"] = HEADER + body
    # Gemini CLI custom command (/vibe-check)
    if '"""' in body:
        raise SystemExit('Skill text must not contain """ (breaks the Gemini TOML adapter).')
    out[ROOT / "adapters/gemini/.gemini/commands/vibe-check.toml"] = (
        "# GENERATED by scripts/build.py. Do not edit by hand.\n"
        f'description = "{DESCRIPTION}"\n'
        'prompt = """\n' + body.replace("\\", "\\\\") + '\n\nUser request: {{args}}\n"""\n'
    )
    out[ROOT / "dist" / "vibe-check.zip"] = skill_zip()
    return out


def zip_entries(data: bytes):
    """What a zip holds: names, permissions and uncompressed contents. Compressed bytes differ
    between zlib versions (Mac vs Linux), so --check compares these, never the raw bytes."""
    import io
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return [(i.filename, i.external_attr, i.date_time, z.read(i)) for i in z.infolist()]


def same(path: Path, content) -> bool:
    if not path.exists():
        return False
    current = path.read_bytes()
    new = content if isinstance(content, bytes) else content.encode()
    if path.suffix == ".zip":
        try:
            return zip_entries(current) == zip_entries(new)
        except zipfile.BadZipFile:
            return False
    return current == new


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not same(path, content):
                stale.append(path.relative_to(ROOT))
        elif not same(path, content):  # don't rewrite an equivalent zip just because zlib differs
            path.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, bytes):
                path.write_bytes(content)
            else:
                path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run `python3 scripts/build.py`):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
