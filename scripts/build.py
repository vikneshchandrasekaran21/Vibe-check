#!/usr/bin/env python3
"""Build single-file and tool-specific versions of the vibe-check skill.

Source of truth: skills/vibe-check/SKILL.md + skills/vibe-check/references/*.md
Outputs:      dist/vibe-check.md and adapters/** (do not edit those by hand)

Usage: python3 scripts/build.py          # write outputs
       python3 scripts/build.py --check  # fail if outputs are out of date (CI)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "skills" / "vibe-check"
REF_ORDER = [
    "security.md",
    "reliability.md",
    "ai-features.md",
    "legal-privacy.md",
    "launch-ux.md",
    "platforms.md",
    "report-template.md",
    "fixes.md",
]
DESCRIPTION = (
    "Pre-launch production-readiness audit for AI-built (vibe-coded) apps: "
    "security, auth, data, reliability, cost, AI features, legal/privacy and UX."
)
HEADER = (
    "<!-- GENERATED by scripts/build.py from skills/vibe-check/. "
    "Do not edit by hand. https://github.com/vikneshchandrasekaran21/vibe-check -->\n\n"
)


def strip_frontmatter(text: str) -> str:
    return re.sub(r"\A---\n.*?\n---\n", "", text, count=1, flags=re.S).lstrip()


def single_file() -> str:
    body = strip_frontmatter((SKILL_DIR / "SKILL.md").read_text())
    # In the single file, references are inlined below, so point to sections instead of files.
    body = re.sub(r"`references/([a-z-]+)\.md`", r"the **\1** section below", body)
    parts = [HEADER, body.rstrip(), "\n\n---\n\n# Reference checklists\n"]
    for name in REF_ORDER:
        ref = (SKILL_DIR / "references" / name).read_text().rstrip()
        ref = re.sub(r"`([a-z-]+)\.md`", r"the **\1** section", ref)
        # demote headings one level so they nest under "Reference checklists"
        ref = re.sub(r"^(#{1,5}) ", lambda m: "#" + m.group(1) + " ", ref, flags=re.M)
        parts.append(f"\n<a id=\"{name[:-3]}\"></a>\n\n{ref}\n")
    return "".join(parts)


def outputs() -> dict[Path, str]:
    full = single_file()
    body = full[len(HEADER):]
    out: dict[Path, str] = {}
    out[ROOT / "dist" / "vibe-check.md"] = full

    # Cursor rule (manual / agent-requested)
    out[ROOT / "adapters/cursor/.cursor/rules/vibe-check.mdc"] = (
        f"---\ndescription: {DESCRIPTION} Use before shipping or when asked to audit the app.\n"
        "globs:\nalwaysApply: false\n---\n\n" + HEADER + body
    )
    # GitHub Copilot prompt file (/vibe-check in Copilot Chat)
    out[ROOT / "adapters/copilot/.github/prompts/vibe-check.prompt.md"] = (
        f"---\nmode: agent\ndescription: {DESCRIPTION}\n---\n\n" + HEADER + body
    )
    # Windsurf workflow (/vibe-check in Cascade)
    out[ROOT / "adapters/windsurf/.windsurf/workflows/vibe-check.md"] = (
        f"---\ndescription: {DESCRIPTION}\n---\n\n" + HEADER + body
    )
    # Cline / Roo workflow (/vibe-check.md)
    out[ROOT / "adapters/cline/.clinerules/workflows/vibe-check.md"] = HEADER + body
    # Gemini CLI custom command (/vibe-check)
    if '"""' in body:
        raise SystemExit('Skill text must not contain """ (breaks the Gemini TOML adapter).')
    out[ROOT / "adapters/gemini/.gemini/commands/vibe-check.toml"] = (
        "# GENERATED by scripts/build.py. Do not edit by hand.\n"
        f'description = "{DESCRIPTION}"\n'
        'prompt = """\n' + body.replace("\\", "\\\\") + '\n\nUser request: {{args}}\n"""\n'
    )
    return out


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date (run `python3 scripts/build.py`):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
